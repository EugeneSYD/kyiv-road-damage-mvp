import folium
import pandas as pd

# 1. Данные по Днепровскому району Киева
data = [
    {
        "id": "DNP-001",
        "location": "Броварской проспект (район м. Левобережная)",
        "cause": "Падение обломков БПЛА",
        "severity": "Средняя (повреждение асфальта)",
        "status": "В ремонте",
        "coords": [[50.4515, 30.5982], [50.4528, 30.6045]]
    },
    {
        "id": "DNP-002",
        "location": "Дарницкая площадь / пр-т Соборности",
        "cause": "Ракетный удар (взрывная волна)",
        "severity": "Высокая (требуется замена полотна)",
        "status": "Ожидает оценки",
        "coords": [[50.4368, 30.6120], [50.4385, 30.6185]]
    },
    {
        "id": "DNP-003",
        "location": "Русановская набережная",
        "cause": "Падение обломков БПЛА",
        "severity": "Низкая (частичное перекрытие полосы)",
        "status": "Восстановлено",
        "coords": [[50.4390, 30.5940], [50.4420, 30.5935]]
    }
]

df = pd.DataFrame(data)

# 2. Создаем карту OpenStreetMap с центром в Днепровском районе Киева
dniprovskyi_map = folium.Map(location=[50.4450, 30.6050], zoom_start=13, tiles="OpenStreetMap")

status_colors = {
    "Ожидает оценки": "red",
    "В ремонте": "orange",
    "Восстановлено": "green"
}

# 3. Наносим поврежденные участки дорог на карту
for _, row in df.iterrows():
    color = status_colors.get(row["status"], "blue")
    popup_text = (
        f"<b>ID:</b> {row['id']}<br>"
        f"<b>Участок:</b> {row['location']}<br>"
        f"<b>Причина:</b> {row['cause']}<br>"
        f"<b>Статус:</b> {row['status']}"
    )

    folium.PolyLine(
        locations=row["coords"],
        color=color,
        weight=6,
        opacity=0.85,
        popup=folium.Popup(popup_text, max_width=300)
    ).add_to(dniprovskyi_map)

# 4. Сохраняем интерактивную карту и таблицу статусов
dniprovskyi_map.save("dniprovskyi_damage_map.html")
df[["id", "location", "cause", "severity", "status"]].to_csv("damage_status_table.csv", index=False)

print("Готово! Файлы созданы.")
